"""Executive PDF Audit Report Exporter for ClauseGuard.

Generates regulator-ready, publication-grade PDF summaries from persisted
AnalysisReport, DiscrepancyFinding, and AuditLog records using pure ReportLab.
"""

import datetime
import io
from typing import Any, Dict, List, Optional
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.units import inch
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    KeepTogether,
    HRFlowable,
)
from reportlab.pdfgen import canvas


class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas for dynamic running header and 'Page X of Y' footer."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica-Bold", 8)
        self.setFillColor(colors.HexColor("#64748B"))

        # Top running header
        self.drawString(54, 11 * inch - 36, "CLAUSEGUARD • EXECUTIVE CLAIM AUDIT & EVIDENCE REPORT")
        self.drawRightString(8.5 * inch - 54, 11 * inch - 36, "CONFIDENTIAL / REGULATORY AUDIT")

        # Top rule
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(54, 11 * inch - 42, 8.5 * inch - 54, 11 * inch - 42)

        # Bottom rule
        self.line(54, 42, 8.5 * inch - 54, 42)

        # Bottom running footer
        self.setFont("Helvetica", 8)
        self.drawString(54, 30, "Generated by ClauseGuard Explainable AI Platform • Advisory Human-in-the-Loop Document")
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(8.5 * inch - 54, 30, page_str)
        self.restoreState()


class AuditReportPDFExporter:
    """Orchestrates in-memory generation of regulator-ready PDF claim audit reports."""

    def __init__(self):
        self.styles = getSampleStyleSheet()
        self._setup_custom_styles()

    def _setup_custom_styles(self):
        base_title = self.styles["Heading1"]
        self.title_style = ParagraphStyle(
            "DocTitle",
            parent=base_title,
            fontName="Helvetica-Bold",
            fontSize=18,
            leading=22,
            textColor=colors.HexColor("#0F172A"),
            spaceAfter=4,
        )
        self.h2_style = ParagraphStyle(
            "SectionH2",
            fontName="Helvetica-Bold",
            fontSize=12,
            leading=16,
            textColor=colors.HexColor("#1E293B"),
            spaceBefore=10,
            spaceAfter=6,
        )
        self.body_style = ParagraphStyle(
            "BodyTextCustom",
            fontName="Helvetica",
            fontSize=8.5,
            leading=11.5,
            textColor=colors.HexColor("#334155"),
        )
        self.body_bold = ParagraphStyle(
            "BodyBoldCustom",
            parent=self.body_style,
            fontName="Helvetica-Bold",
        )
        self.caption_style = ParagraphStyle(
            "CaptionCustom",
            fontName="Helvetica-Oblique",
            fontSize=7.5,
            leading=10,
            textColor=colors.HexColor("#64748B"),
        )
        self.badge_style = ParagraphStyle(
            "VerdictBadge",
            fontName="Helvetica-Bold",
            fontSize=13,
            leading=16,
            alignment=1,  # Center
        )

    def generate_pdf(
        self,
        report: Any,
        claim: Any,
        policy: Optional[Any] = None,
        findings: Optional[List[Any]] = None,
        audit_logs: Optional[List[Any]] = None,
        model_used: Optional[str] = "Gemini 1.5 Pro (via ClauseGuard LangGraph Engine)",
    ) -> bytes:
        """Renders comprehensive PDF report bytes directly in memory."""
        buf = io.BytesIO()
        doc = SimpleDocTemplate(
            buf,
            pagesize=letter,
            leftMargin=54,
            rightMargin=54,
            topMargin=54,
            bottomMargin=54,
        )

        story = []

        # Safely extract trace metadata
        trace: Dict[str, Any] = getattr(report, "agent_trace", {}) or {}
        if isinstance(trace, str):
            import json
            try:
                trace = json.loads(trace)
            except Exception:
                trace = {}
        verdict_str = trace.get("verdict") or (report.recommendation.value.upper() if hasattr(report.recommendation, "value") else str(report.recommendation).upper())
        override_data = trace.get("override")
        fallback_used = trace.get("fallback_used", False)
        fallback_reason = trace.get("fallback_reason")

        # ======================================================================
        # SECTION 1: HEADER & METADATA
        # ======================================================================
        story.append(Paragraph("🛡️ CLAUSEGUARD EXECUTIVE AUDIT REPORT", self.title_style))
        story.append(
            Paragraph(
                "Automated Insurance Fraud Detection, Clause Verification & Policy Loophole Audit Summary",
                self.caption_style,
            )
        )
        story.append(Spacer(1, 8))

        gen_time = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
        meta_table_data = [
            [
                Paragraph(f"<b>Report ID:</b> #{report.id}", self.body_style),
                Paragraph(f"<b>Claim Reference:</b> {claim.claim_number if claim else 'N/A'}", self.body_style),
                Paragraph(f"<b>Generated:</b> {gen_time}", self.body_style),
            ],
            [
                Paragraph(f"<b>Claimant:</b> {claim.claimant_name if claim else 'N/A'}", self.body_style),
                Paragraph(f"<b>Policy Number:</b> {policy.policy_number if policy else 'N/A'}", self.body_style),
                Paragraph(f"<b>Model Provenance:</b> {model_used}", self.body_style),
            ],
            [
                Paragraph(f"<b>Claimed Amount:</b> ${claim.claimed_amount:,.2f}" if claim else "$0.00", self.body_style),
                Paragraph(f"<b>Policy Insurer:</b> {policy.insurer_name if policy else 'Apex Mutual Assurance'}", self.body_style),
                Paragraph(f"<b>Incident Date:</b> {claim.incident_date if claim else 'N/A'}", self.body_style),
            ],
        ]
        meta_table = Table(meta_table_data, colWidths=[2.2 * inch, 2.4 * inch, 2.5 * inch])
        meta_table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
                    ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                    ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
                    ("TOPPADDING", (0, 0), (-1, -1), 4),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ]
            )
        )
        story.append(meta_table)
        story.append(Spacer(1, 10))

        # FALLBACK WARNING BANNER IF APPLICABLE
        if fallback_used:
            fb_text = (
                f"<b>⚡ MODEL FALLBACK WARNING:</b> This analysis was performed in fallback/degraded mode "
                f"({fallback_reason or 'local heuristic / offline provider'}). "
                f"Findings and clause interpretations must be confirmed by human legal counsel before final action."
            )
            fb_table = Table([[Paragraph(fb_text, self.body_style)]], colWidths=[7.1 * inch])
            fb_table.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#FEF3C7")),
                        ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#F59E0B")),
                        ("TOPPADDING", (0, 0), (-1, -1), 6),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                        ("LEFTPADDING", (0, 0), (-1, -1), 8),
                    ]
                )
            )
            story.append(fb_table)
            story.append(Spacer(1, 10))

        # ======================================================================
        # SECTION 2: "SHOULD WE TAKE THIS?" DECISION BOX
        # ======================================================================
        story.append(Paragraph("1. Executive Decision Summary", self.h2_style))

        if "DO_NOT_TAKE" in verdict_str:
            v_color = colors.HexColor("#DC2626")
            v_bg = colors.HexColor("#FEE2E2")
            v_title = "DO NOT TAKE (CRITICAL BLOCKERS DETECTED)"
        elif "TAKE" in verdict_str and "NOT" not in verdict_str:
            v_color = colors.HexColor("#16A34A")
            v_bg = colors.HexColor("#DCFCE7")
            v_title = "TAKE (RECOMMENDED FOR POSITIVE REVIEW)"
        else:
            v_color = colors.HexColor("#D97706")
            v_bg = colors.HexColor("#FEF3C7")
            v_title = "REVIEW REQUIRED (MANUAL ESCALATION)"

        box_p = Paragraph(f"<font color='{v_color.hexval()}'>{v_title}</font>", self.badge_style)
        verdict_box = Table([[box_p]], colWidths=[7.1 * inch])
        verdict_box.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, -1), v_bg),
                    ("BOX", (0, 0), (-1, -1), 1.5, v_color),
                    ("TOPPADDING", (0, 0), (-1, -1), 8),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
                ]
            )
        )
        story.append(verdict_box)
        story.append(Spacer(1, 6))

        # OVERRIDE NOTICE IF RECORDED
        if override_data:
            ov_text = (
                f"<b>⚖️ ADJUDICATOR OVERRIDE RECORDED:</b><br/>"
                f"Final Status: <b>{override_data.get('final_verdict')}</b> (Original Gate: {verdict_str})<br/>"
                f"Signed by: <b>{override_data.get('adjudicator_name')}</b> on {override_data.get('timestamp')}<br/>"
                f"Justification: <i>{override_data.get('justification')}</i>"
            )
            ov_table = Table([[Paragraph(ov_text, self.body_style)]], colWidths=[7.1 * inch])
            ov_table.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#EFF6FF")),
                        ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#3B82F6")),
                        ("TOPPADDING", (0, 0), (-1, -1), 6),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                    ]
                )
            )
            story.append(ov_table)
            story.append(Spacer(1, 6))

        # Metrics & Summary
        score = report.overall_risk_score
        confidence = report.confidence_score
        summary_p = Paragraph(f"<b>Risk Score:</b> {score:.1f}/100 &nbsp;|&nbsp; <b>Confidence:</b> {confidence * 100:.0f}% (heuristic) &nbsp;|&nbsp; <b>Advisory Only</b>: Does not constitute a binding legal adjudication.", self.body_style)
        story.append(summary_p)
        story.append(Spacer(1, 4))

        # Top reasons
        top_reasons = trace.get("top_reasons", [])
        if top_reasons:
            story.append(Paragraph("<b>Primary Decision Drivers:</b>", self.body_bold))
            for r in top_reasons:
                story.append(Paragraph(f"• {r}", self.body_style))
            story.append(Spacer(1, 4))

        # Conditions to flip verdict
        conditions = trace.get("conditions_to_change_verdict", [])
        if conditions:
            story.append(Paragraph("<b>Conditions Required to Re-evaluate Verdict:</b>", self.body_bold))
            for c in conditions:
                story.append(Paragraph(f"• {c}", self.body_style))

        story.append(Spacer(1, 10))

        # ======================================================================
        # SECTION 3: TRACK A — FRAUD INDICATORS & CONTRADICTIONS
        # ======================================================================
        story.append(Paragraph("2. Track A — Claim Fraud Indicators & Document Contradictions", self.h2_style))
        story.append(Paragraph("Objective discrepancies and material timeline contradictions noted during document cross-examination. <i>Notice: Discrepancies alone do not constitute legal proof of fraud.</i>", self.caption_style))
        story.append(Spacer(1, 4))

        discrepancies = findings or []
        # Deduplicate findings by title and finding_type if multiple runs created identical findings
        seen_keys = set()
        deduped_findings = []
        for f in discrepancies:
            k = (f.title, getattr(f.finding_type, "value", str(f.finding_type)))
            if k not in seen_keys:
                seen_keys.add(k)
                deduped_findings.append(f)
        discrepancies = deduped_findings
        if discrepancies:
            f_table_data = [
                [
                    Paragraph("<b>ID</b>", self.body_bold),
                    Paragraph("<b>Severity</b>", self.body_bold),
                    Paragraph("<b>Finding & Policy Citation</b>", self.body_bold),
                    Paragraph("<b>Evidence & Recommendation</b>", self.body_bold),
                ]
            ]
            for f in discrepancies:
                sev_val = (f.severity.value if hasattr(f.severity, "value") else str(f.severity)).lower()
                sev_color = "#DC2626" if sev_val == "critical" else "#EA580C" if sev_val == "high" else "#CA8A04"
                f_table_data.append(
                    [
                        Paragraph(f"#{f.id}", self.body_style),
                        Paragraph(f"<font color='{sev_color}'><b>{sev_val.upper()}</b></font>", self.body_style),
                        Paragraph(f"<b>{f.title}</b><br/>Citation: <code>{f.policy_reference or 'General'}</code><br/>{f.description}", self.body_style),
                        Paragraph(f"<b>Evidence:</b> {f.evidence_snippet or 'None'}<br/><b>Action:</b> {f.suggested_action or 'Verify'}", self.body_style),
                    ]
                )
            f_table = Table(f_table_data, colWidths=[0.5 * inch, 0.9 * inch, 3.1 * inch, 2.6 * inch])
            f_table.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F1F5F9")),
                        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
                        ("VALIGN", (0, 0), (-1, -1), "TOP"),
                        ("TOPPADDING", (0, 0), (-1, -1), 4),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                    ]
                )
            )
            story.append(f_table)
        else:
            story.append(Paragraph("No objective fraud indicators or document contradictions recorded.", self.body_style))

        # Missing documents
        missing_docs = trace.get("missing_documents", [])
        if missing_docs:
            story.append(Spacer(1, 4))
            story.append(Paragraph("<b>Missing Mandatory Proof of Claim:</b>", self.body_bold))
            for m in missing_docs:
                story.append(Paragraph(f"• [MISSING] {m}", self.body_style))

        story.append(Spacer(1, 10))

        # ======================================================================
        # SECTION 4: TRACK B — POLICY & SCHEME LOOPHOLES
        # ======================================================================
        story.append(Paragraph("3. Track B — Policy Contract Loopholes & Ambiguities", self.h2_style))
        story.append(Paragraph("Policy drafting ambiguities and scheme gaming vulnerabilities identified in contract terms. <i>Strictly separated from claimant fraud indicators.</i>", self.caption_style))
        story.append(Spacer(1, 4))

        loophole_text = getattr(report, "loophole_analysis", None)
        if loophole_text:
            lh_table = Table([[Paragraph(f"<b>Identified Ambiguities:</b><br/>{loophole_text.replace(chr(10), '<br/>')}", self.body_style)]], colWidths=[7.1 * inch])
            lh_table.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
                        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#818CF8")),
                        ("TOPPADDING", (0, 0), (-1, -1), 6),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                    ]
                )
            )
            story.append(lh_table)
        else:
            story.append(Paragraph("No policy contract loopholes flagged for reviewed clauses.", self.body_style))

        story.append(Spacer(1, 10))

        # ======================================================================
        # SECTION 5: CITED CLAUSES & EVIDENCE VERIFICATION
        # ======================================================================
        story.append(Paragraph("4. Cited Policy Clauses & Evidence Verification", self.h2_style))
        approved_clauses = trace.get("approved_clause_refs", [])
        if approved_clauses:
            clause_str = ", ".join(f"<code>{c}</code>" for c in approved_clauses[:18])
            if len(approved_clauses) > 18:
                clause_str += f" (+{len(approved_clauses) - 18} more)"
            story.append(Paragraph(f"<b>Reviewer-Approved Applicable Clauses:</b> {clause_str}", self.body_style))
        else:
            story.append(Paragraph("No specific clauses approved by Reviewer node.", self.body_style))
        story.append(Spacer(1, 10))

        # ======================================================================
        # SECTION 6: CALCULATIONS & FINANCIAL AUDIT STEPS
        # ======================================================================
        story.append(Paragraph("5. Financial Calculations & Sub-Limit Audit Steps", self.h2_style))
        calc_steps = trace.get("calculation_steps", [])
        if calc_steps:
            c_data = [[Paragraph("<b>Step</b>", self.body_bold), Paragraph("<b>Calculation & Rule Applied</b>", self.body_bold)]]
            for idx, cs in enumerate(calc_steps, 1):
                c_data.append([Paragraph(str(idx), self.body_style), Paragraph(cs, self.body_style)])
            c_table = Table(c_data, colWidths=[0.5 * inch, 6.6 * inch])
            c_table.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F1F5F9")),
                        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
                        ("VALIGN", (0, 0), (-1, -1), "TOP"),
                        ("TOPPADDING", (0, 0), (-1, -1), 3),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                    ]
                )
            )
            story.append(c_table)
        else:
            story.append(Paragraph("No calculation audit steps recorded.", self.body_style))

        story.append(Spacer(1, 10))

        # ======================================================================
        # SECTION 7: RECOMMENDED MANUAL CHECKS & ADJUDICATOR SIGN-OFF
        # ======================================================================
        story.append(Paragraph("6. Recommended Manual Checks & Adjudicator Sign-Off", self.h2_style))
        unresolved = trace.get("unresolved_issues", [])
        if unresolved:
            story.append(Paragraph("<b>Actionable Verification Items:</b>", self.body_bold))
            for u in unresolved:
                story.append(Paragraph(f"[ ] {u}", self.body_style))
            story.append(Spacer(1, 6))

        # Sign-off box
        signoff_data = [
            [
                Paragraph("<b>Adjudicator Digital Sign-Off:</b>", self.body_bold),
                Paragraph("<b>Date / Timestamp:</b>", self.body_bold),
                Paragraph("<b>Override Justification:</b>", self.body_bold),
            ],
            [
                Paragraph(override_data.get("adjudicator_name", "_______________________") if override_data else "_______________________", self.body_style),
                Paragraph(override_data.get("timestamp", "_______________________") if override_data else "_______________________", self.body_style),
                Paragraph(override_data.get("justification", "None / Gate Default Upheld") if override_data else "None / Gate Default Upheld", self.body_style),
            ],
        ]
        sign_table = Table(signoff_data, colWidths=[2.3 * inch, 2.3 * inch, 2.5 * inch])
        sign_table.setStyle(
            TableStyle(
                [
                    ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#94A3B8")),
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F8FAFC")),
                    ("TOPPADDING", (0, 0), (-1, -1), 5),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ]
            )
        )
        story.append(sign_table)
        story.append(Spacer(1, 10))

        # ======================================================================
        # SECTION 8: CHRONOLOGICAL AUDIT LOG APPENDIX
        # ======================================================================
        story.append(Paragraph("7. Chronological Audit Trail Appendix", self.h2_style))
        logs = audit_logs or []
        if logs:
            l_data = [
                [
                    Paragraph("<b>Timestamp (UTC)</b>", self.body_bold),
                    Paragraph("<b>Action</b>", self.body_bold),
                    Paragraph("<b>Details / Audit Event Description</b>", self.body_bold),
                ]
            ]
            for l in logs[-8:]:  # Show up to 8 most recent chronological logs
                ts_str = l.created_at.strftime("%Y-%m-%d %H:%M:%S") if hasattr(l, "created_at") and l.created_at else "N/A"
                l_data.append(
                    [
                        Paragraph(ts_str, self.body_style),
                        Paragraph(f"<code>{l.action}</code>", self.body_style),
                        Paragraph(l.details or "", self.body_style),
                    ]
                )
            l_table = Table(l_data, colWidths=[1.6 * inch, 1.8 * inch, 3.7 * inch])
            l_table.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F1F5F9")),
                        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
                        ("VALIGN", (0, 0), (-1, -1), "TOP"),
                        ("TOPPADDING", (0, 0), (-1, -1), 3),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                    ]
                )
            )
            story.append(l_table)
        else:
            story.append(Paragraph("No audit log events recorded for this entity.", self.body_style))

        # Build Document
        doc.build(story, canvasmaker=NumberedCanvas)
        return buf.getvalue()


# Global reusable exporter instance
_pdf_exporter: Optional[AuditReportPDFExporter] = None


def get_pdf_exporter() -> AuditReportPDFExporter:
    """Returns singleton instance of the PDF exporter."""
    global _pdf_exporter
    if _pdf_exporter is None:
        _pdf_exporter = AuditReportPDFExporter()
    return _pdf_exporter
